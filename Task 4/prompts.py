# Ответ, который бот даёт, когда в базе не нашлось релевантной информации.
DONT_KNOW_ANSWER = "Я не знаю."


def format_context(chunks):
    """Собирает найденные чанки в один текстовый блок с источниками.

    Аргумент `chunks` - список словарей с ключами `text`, `source`,
    `chunk_index`. Возвращает строку, которую подставляют в {context}.
    """
    parts = []
    for i, ch in enumerate(chunks, 1):
        src = ch.get("source", "?")
        idx = ch.get("chunk_index", 0)
        text = ch.get("text", "").strip()
        parts.append(f"[{i}] источник: {src} (чанк {idx})\n{text}")
    return "\n\n".join(parts)
